"""Generate TFT_eSPI smooth fonts (VLW format, anti-aliased) from TTF files.

Output: firmware/include/fonts/<name>.h, each holding a PROGMEM byte array that
can be passed straight to tft.loadFont(). Also writes a preview PNG decoded from
the generated bytes (so the preview proves the VLW data itself is correct).

Usage (from the repo root):
    .venv/Scripts/python tools/make_fonts.py

VLW layout (big-endian int32 throughout), as read by TFT_eSPI Smooth_font.cpp:
    header : glyphCount, version, pointSize, 0, ascent, descent
    glyphs : glyphCount x (unicode, height, width, xAdvance, dY, dX, 0)
    bitmaps: per glyph, width*height bytes of 8-bit alpha, row-major
dY = distance from the baseline up to the bitmap's top edge; dX = left offset.
"""

from __future__ import annotations

import struct
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets" / "fonts" / "inter"
OUT_DIR = ROOT / "firmware" / "include" / "fonts"
PREVIEW = ROOT / "assets" / "fonts" / "preview.png"

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
EXTRAS = "°·•–…"            # degree, middle dot, bullet, en dash, ellipsis
TEXT = ASCII + EXTRAS
DIGITS_CLOCK = " 0123456789:-"
DIGITS_TEMP = " 0123456789-°"


@dataclass(frozen=True)
class Spec:
    name: str        # C identifier and file name
    ttf: str
    size: int        # em size in pixels
    chars: str
    purpose: str


SPECS = [
    Spec("inter_clock_60", "Inter-500.ttf", 60, DIGITS_CLOCK, "Home clock digits"),
    Spec("inter_temp_40", "Inter-500.ttf", 40, DIGITS_TEMP, "Large temperature"),
    Spec("inter_title_22", "Inter-600.ttf", 22, TEXT, "Screen titles, emphasis"),
    Spec("inter_body_16", "Inter-400.ttf", 16, TEXT, "Body text, event titles"),
    Spec("inter_label_13", "Inter-500.ttf", 13, TEXT, "Captions, labels, chips"),
]


@dataclass
class Glyph:
    code: int
    width: int
    height: int
    advance: int
    dy: int
    dx: int
    bitmap: bytes


def has_glyph(font: ImageFont.FreeTypeFont, ch: str) -> bool:
    """Missing characters render as the .notdef box; compare against a private-use char."""
    if ch == " ":
        return True
    return _ink(font, ch) != _ink(font, "")


def _ink(font: ImageFont.FreeTypeFont, ch: str) -> bytes:
    left, top, right, bottom = font.getbbox(ch)
    img = Image.new("L", (max(1, right - left), max(1, bottom - top)), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
    return f"{left},{top},{right},{bottom}".encode() + img.tobytes()


def render_glyph(font: ImageFont.FreeTypeFont, ch: str) -> Glyph:
    advance = round(font.getlength(ch))
    left, top, right, bottom = font.getbbox(ch, anchor="ls")  # relative to baseline origin
    w, h = right - left, bottom - top
    if ch == " " or w <= 0 or h <= 0:
        return Glyph(ord(ch), 0, 0, advance, 0, 0, b"")
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    ink = img.getbbox()                     # tighten to actual ink
    if ink is None:
        return Glyph(ord(ch), 0, 0, advance, 0, 0, b"")
    img = img.crop(ink)
    left += ink[0]
    top += ink[1]
    w, h = img.size
    for v in (w, h, advance):
        if v > 255:
            raise ValueError(f"glyph {ch!r} too large for VLW uint8 fields ({v})")
    return Glyph(ord(ch), w, h, advance, -top, left, img.tobytes())


def build_vlw(spec: Spec) -> tuple[bytes, list[Glyph], int, int]:
    font = ImageFont.truetype(str(FONT_DIR / spec.ttf), spec.size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in dict.fromkeys(spec.chars):    # de-duplicate, keep order
        if not has_glyph(font, ch):
            print(f"  ! {spec.name}: {ch!r} (U+{ord(ch):04X}) not in font, skipped")
            continue
        glyphs.append(render_glyph(font, ch))
    out = bytearray(struct.pack(">6i", len(glyphs), 11, spec.size, 0, ascent, descent))
    for g in glyphs:
        out += struct.pack(">7i", g.code, g.height, g.width, g.advance, g.dy, g.dx, 0)
    for g in glyphs:
        out += g.bitmap
    return bytes(out), glyphs, ascent, descent


def write_header(spec: Spec, data: bytes, glyph_count: int) -> Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{spec.name}.h"
    lines = [
        "#pragma once",
        "// GENERATED by tools/make_fonts.py - do not edit.",
        f"// {spec.ttf} @ {spec.size}px, {glyph_count} glyphs, {len(data)} bytes. {spec.purpose}.",
        "// Inter is licensed under the SIL Open Font License 1.1 (assets/fonts/inter/OFL.txt).",
        "#include <pgmspace.h>",
        "",
        f"const uint8_t {spec.name}[] PROGMEM = {{",
    ]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
    lines.append("};")
    path.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    return path


# ---------- preview: decode the VLW bytes exactly as the firmware would ----------

def decode_vlw(data: bytes):
    count, _ver, _size, _z, ascent, descent = struct.unpack_from(">6i", data, 0)
    off, glyphs = 24, {}
    metrics = [struct.unpack_from(">7i", data, off + 28 * i) for i in range(count)]
    bmp = off + 28 * count
    for code, h, w, adv, dy, dx, _ in metrics:
        glyphs[code] = (w, h, adv, dy, dx, data[bmp:bmp + w * h])
        bmp += w * h
    if bmp != len(data):
        raise ValueError("VLW size mismatch")
    max_ascent = max([ascent] + [g[3] for c, g in glyphs.items() if c > 0x20])
    return glyphs, max_ascent


def draw_vlw(canvas: Image.Image, data: bytes, text: str, x: int, y: int, rgb) -> None:
    glyphs, max_ascent = decode_vlw(data)
    for ch in text:
        g = glyphs.get(ord(ch))
        if g is None:
            continue
        w, h, adv, dy, dx, bitmap = g
        if w and h:
            mask = Image.frombytes("L", (w, h), bitmap)
            canvas.paste(Image.new("RGB", (w, h), rgb), (x + dx, y + max_ascent - dy), mask)
        x += adv


def make_preview(built: dict[str, bytes]) -> None:
    bg, cyan, white, grey = (0x12, 0x14, 0x17), (0x00, 0xD1, 0xFF), (255, 255, 255), (0x8A, 0x92, 0x9C)
    img = Image.new("RGB", (320, 240), bg)            # actual screen size
    draw_vlw(img, built["inter_clock_60"], "2:32", 12, 6, white)
    draw_vlw(img, built["inter_temp_40"], "54°", 210, 14, white)
    draw_vlw(img, built["inter_label_13"], "Partly cloudy · H 61° L 44°", 186, 70, grey)
    draw_vlw(img, built["inter_title_22"], "Friday, November 7", 14, 96, white)
    draw_vlw(img, built["inter_label_13"], "TODAY", 14, 150, cyan)
    draw_vlw(img, built["inter_body_16"], "Dinner with Sam's parents", 70, 148, white)
    draw_vlw(img, built["inter_label_13"], "6:30 PM", 260, 150, grey)
    draw_vlw(img, built["inter_label_13"], "SAT", 14, 180, cyan)
    draw_vlw(img, built["inter_body_16"], "Farmers market…", 70, 178, white)
    draw_vlw(img, built["inter_label_13"], "9:00 AM", 260, 180, grey)
    img.resize((960, 720), Image.NEAREST).save(PREVIEW)


def main() -> None:
    built = {}
    for spec in SPECS:
        data, glyphs, ascent, descent = build_vlw(spec)
        path = write_header(spec, data, len(glyphs))
        decode_vlw(data)  # self-check
        built[spec.name] = data
        print(f"{spec.name:16} {len(glyphs):3} glyphs  {len(data):6} bytes  "
              f"ascent={ascent} descent={descent}  -> {path.relative_to(ROOT)}")
    make_preview(built)
    print(f"preview -> {PREVIEW.relative_to(ROOT)}")
    print(f"total flash: {sum(len(d) for d in built.values())} bytes")


if __name__ == "__main__":
    main()
